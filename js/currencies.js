// Find a currency code from a code, symbol or legacy value (used when importing old data).
export function currencyFrom(v, fallback = "USD") {
  const x = String(v ?? "").trim();
  if (!x) return fallback;
  const up = x.toUpperCase();
  if (CURRENCY[up]) return up;
  const bySym = CURRENCIES.find(c => c[1] === x);
  return bySym ? bySym[0] : fallback;
}
